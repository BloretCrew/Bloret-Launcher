_COUNTRY_CODES = frozenset(row[0] for row in _COUNTRIES)


def _locale_name(language: str) -> str:
    """Map a launcher language code to a Qt locale used for names and sorting."""
    value = str(language or "").strip()
    mapping = {
        "zh-cn": "zh_CN",
        "zh-TW": "zh_TW",
        "zh-wy": "zh_CN",
        "gt-ZH": "zh_CN",
        "en-GB": "en_GB",
        "ja-JP": "ja_JP",
        "ru-RU": "ru_RU",
    }
    if value in mapping:
        return mapping[value]
    lowered = value.lower()
    if lowered.startswith("zh"):
        return "zh_TW" if "tw" in lowered else "zh_CN"
    if lowered.startswith("ja"):
        return "ja_JP"
    if lowered.startswith("ru"):
        return "ru_RU"
    if lowered.startswith("en"):
        return "en_GB"
    return "en_US"


def _name_index(language: str) -> int:
    locale_name = _locale_name(language)
    if locale_name == "zh_CN":
        return 2
    if locale_name == "zh_TW":
        return 3
    if locale_name == "ja_JP":
        return 4
    if locale_name == "ru_RU":
        return 5
    return 1


def country_options(language: str) -> list[dict]:
    """Return every country/region as ``{"code": ..., "name": ...}``."""
    index = _name_index(language)
    options = []
    for row in _COUNTRIES:
        name = row[index]
        if row[0] == "CN":
            if index == 2:
                name = "中国大陆"
            elif index == 3:
                name = "中國大陸"
        options.append({"code": row[0], "name": name})

    try:
        collator = QCollator(QLocale(_locale_name(language)))
        options.sort(key=lambda item: collator.sortKey(item["name"]))
    except Exception:
        options.sort(key=lambda item: item["name"].casefold())
    return options


def _normalize_region_code(value) -> str:
    code = str(value or "").strip().upper()
    return code if code in _COUNTRY_CODES else ""


def system_country_code() -> str:
    """Detect the system country/region, falling back to ``US``."""
    try:
        locale_name = QLocale.system().name().replace("-", "_")
        if "_" in locale_name:
            code = _normalize_region_code(locale_name.rsplit("_", 1)[-1])
            if code:
                return code
        code = _normalize_region_code(
            QLocale.territoryToCode(QLocale.system().territory())
        )
        if code:
            return code
    except Exception:
        pass

    for variable in ("LC_ALL", "LC_CTYPE", "LANG"):
        raw = os.environ.get(variable, "")
        base = raw.split(".", 1)[0].split("@", 1)[0].replace("-", "_")
        if "_" in base:
            code = _normalize_region_code(base.rsplit("_", 1)[-1])
            if code:
                return code
    return "US"


def is_region_unavailable(country_code: str) -> bool:
    """Mainland China is the only region blocked by the OOBE gate."""
    return str(country_code or "").strip().upper() == "CN"
